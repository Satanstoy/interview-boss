CLUSTER_LABEL_PROMPT = """你是面试题题库管理专家。下面是一批【已有题目聚类】的原始题面列表，请为每个聚类生成一个**规范标签**。

要求：
1. label：用一句话概括该聚类的规范题面（20 字以内，作为该聚类的"记忆标签"）
2. keywords：3-6 个关键词，覆盖该聚类下所有原始题面
3. 只输出 JSON 对象，不要输出其他内容

输入格式（每行一个聚类）：
每行中 `|` 分隔的其余字段为该聚类的原始题面变体
{qb_id} | {questions}

输出格式（严格 JSON 对象，不要输出其他内容）：
{{"clusters": [{{"qb_id": {qb_id}, "label": "...", "keywords": ["...", "..."]}}, ...]}}"""

SINGLETON_ASSIGN_PROMPT = """你是面试题去重专家。下面有一道【新题目】和一批【已有聚类标签】。请判断新题目应该归入哪个已有聚类，还是作为独立新题。

判断标准：
- **应合并**：表述不同但考察点完全相同（如"怎样做限流？"与"限流方案有哪些？"、"如何评估Agent的产出"与"怎么评价Agent的输出质量"）
- **不应合并**（宁可漏合并，不可错合并）：
  1. 考察点不同：如"TCP三次握手和四次挥手的过程"与"IO多路复用"（同属计算机网络但知识点不同）
  2. 主题相近但问题不同：如"缓存的使用场景"与"缓存穿透击穿雪崩怎么解决"（一个问场景一个问问题解法）
  3. 介绍/概念题 vs 对比题：如"LangChain的核心部分和作用"与"LangGraph和LangChain的区别"
  4. 具体算法题 vs 元问题：如"合并两个有序链表"与"口述算法题的解题思路"
  5. 考察范围不同：如"Redis有哪些数据结构"与"Redis跳表实现"
- 没有匹配时不要强行归入，返回 null

输出格式（严格 JSON，不要输出其他内容）：
{{"match": {qb_id} 或 null, "reason": "一句话原因"}}"""

